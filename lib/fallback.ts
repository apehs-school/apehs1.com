export function eventsByDate(items: { date: string; title: string }[]) {
  return items.reduce<Record<string, string[]>>((map, item) => {
    const list = map[item.date] ?? [];
    list.push(item.title);
    map[item.date] = list;
    return map;
  }, {});
}
